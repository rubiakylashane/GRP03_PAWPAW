ALTER TABLE appointment
  ADD CONSTRAINT chk_appointment_status CHECK (
    status IN (
      'Pending',
      'Scheduled',
      'Approved',
      'Checked-in',
      'In Progress',
      'Completed',
      'Cancelled',
      'No-show'
    )
  );

ALTER TABLE owner
  ADD COLUMN IF NOT EXISTS first_name character varying,
  ADD COLUMN IF NOT EXISTS middle_name character varying,
  ADD COLUMN IF NOT EXISTS last_name character varying,
  ADD COLUMN IF NOT EXISTS photo text;

ALTER TABLE pet
  ADD COLUMN IF NOT EXISTS allergies text,
  ADD COLUMN IF NOT EXISTS notes text,
  ADD COLUMN IF NOT EXISTS photo text;

ALTER TABLE vaccination
  ALTER COLUMN veterinarian_id DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS administered_by character varying;

CREATE TABLE IF NOT EXISTS notification (
  notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES user_account(user_id) ON DELETE CASCADE,
  notification_type character varying NOT NULL,
  title character varying NOT NULL,
  message text NOT NULL,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at timestamp without time zone
);

CREATE INDEX IF NOT EXISTS idx_notification_user_created
  ON notification (user_id, created_at DESC);
